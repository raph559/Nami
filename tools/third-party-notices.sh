#!/bin/bash
# Regenerates THIRD_PARTY_NOTICES.md from the Go modules linked into the engine
# and the vendored native components. Run in WSL after changing engine/go.mod.
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
source "$root/env.sh"
out="$root/THIRD_PARTY_NOTICES.md"

detect() {
  local f="$1"
  if grep -q "Mozilla Public License" "$f"; then echo "MPL-2.0"
  elif grep -q "Apache License" "$f"; then echo "Apache-2.0"
  elif grep -q "GNU LESSER GENERAL PUBLIC" "$f"; then echo "LGPL"
  elif grep -q "GNU GENERAL PUBLIC" "$f"; then echo "GPL"
  elif grep -qi "Permission is hereby granted, free of charge" "$f"; then echo "MIT"
  elif grep -qi "ISC License\|Permission to use, copy, modify, and/or distribute" "$f"; then echo "ISC"
  elif grep -qi "Redistribution and use in source and binary forms" "$f"; then
    if grep -qi "Neither the name" "$f"; then echo "BSD-3-Clause"; else echo "BSD-2-Clause"; fi
  elif grep -qi "unlicense\|public domain" "$f"; then echo "Public domain"
  else echo "see license file"; fi
}

{
  echo "# Third-party notices"
  echo
  echo "Nami is licensed under GPL-3.0. It includes the components below, each under its own license."
  echo
  echo "## Native components"
  echo
  echo "| Component | License | Notes |"
  echo "|---|---|---|"
  echo "| [MobileVLCKit](https://code.videolan.org/videolan/VLCKit) 3.7.4 | LGPL-2.1 | Dynamically linked framework, shipped unmodified in the IPA |"
  echo
  echo "## Go modules in the torrent engine"
  echo
  echo "Generated by \`tools/third-party-notices.sh\` from the packages actually compiled into \`libnami.a\`."
  echo
  echo "| Module | Version | License |"
  echo "|---|---|---|"
  cd "$root/engine"
  GOOS=ios GOARCH=arm64 CGO_ENABLED=1 go list -tags nosqlite -deps -f '{{with .Module}}{{if not .Main}}{{.Path}} {{.Version}} {{.Dir}}{{end}}{{end}}' . \
    | sort -u | while read -r path version dir; do
      lic=$(ls "$dir" 2>/dev/null | grep -iE '^(LICEN[CS]E|COPYING)' | head -1 || true)
      if [ -n "$lic" ]; then kind=$(detect "$dir/$lic"); else kind="no license file"; fi
      echo "| [$path](https://pkg.go.dev/$path) | $version | $kind |"
    done
} > "$out"
echo "wrote $out ($(grep -c '^| \[' "$out") entries)"
